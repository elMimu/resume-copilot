"use client";

import { FormEvent, useState } from "react";
import { ZodError } from "zod";

import { saveJobResult } from "@/db/job-results";

export function JobResultImport({ jobId }: { jobId: string }) {
  const [value, setValue] = useState("");
  const [error, setError] = useState<string | null>(null);

  async function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setError(null);

    try {
      const json: unknown = JSON.parse(value);

      await saveJobResult(jobId, json);

      setValue("");
    } catch (error) {
      if (error instanceof SyntaxError) {
        setError("Invalid JSON.");
        return;
      }

      if (error instanceof ZodError) {
        setError("JSON does not match the Resume Copilot schema.");
        return;
      }

      setError("Could not import generated result.");
    }
  }

  return (
    <form onSubmit={handleSubmit} className="rounded border p-6">
      <h2 className="font-semibold">Import generated result</h2>

      <p className="mt-2 text-sm text-gray-500">
        Paste the JSON generated by Codex.
      </p>

      <textarea
        value={value}
        onChange={(event) => setValue(event.target.value)}
        rows={14}
        spellCheck={false}
        className="mt-4 w-full rounded border p-3 font-mono text-sm"
      />

      {error && <p className="mt-3 text-sm text-red-600">{error}</p>}

      <button
        type="submit"
        className="mt-4 rounded bg-black px-4 py-2 text-white"
      >
        Import
      </button>
    </form>
  );
}
